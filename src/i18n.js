  let current = DEFAULT;

  function available() { return Object.keys(DICT); }
  function detect() {
    try { const v = localStorage.getItem(STORAGE_KEY); if (v && DICT[v]) return v; } catch (_) { /* storage unavailable */ }
    return DEFAULT;
  }
  function language() { return current; }
  function setLanguage(lang) {
    current = DICT[lang] ? lang : DEFAULT;
    try { localStorage.setItem(STORAGE_KEY, current); } catch (_) { /* storage unavailable */ }
    return current;
  }
  function t(key, vars) {
    const table = DICT[current] || DICT[DEFAULT];
    let s = key in table ? table[key] : (key in DICT[DEFAULT] ? DICT[DEFAULT][key] : key);
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
    return s;
  }
  // Translate static markup: data-i18n (text), data-i18n-placeholder, data-i18n-title, data-i18n-aria (aria-label).
  function apply(root) {
    const scope = root || (typeof document !== "undefined" ? document : null);
    if (!scope) return;
    scope.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.getAttribute("data-i18n")); });
    scope.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder"))); });
    scope.querySelectorAll("[data-i18n-title]").forEach((el) => { el.setAttribute("title", t(el.getAttribute("data-i18n-title"))); });
    scope.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria"))); });
    if (scope === document) {
      document.documentElement.setAttribute("lang", t("html.lang"));
      document.title = t("app.title");
      const meta = document.querySelector('meta[name="description"]'); if (meta) meta.setAttribute("content", t("app.description"));
    }
  }

  return { t, apply, setLanguage, language, detect, available, DICT, STORAGE_KEY, DEFAULT };
